// house-types.ts — the house as TypeScript: every entity id with its possible states,
// generated from Home Assistant's live states. Rules then get completion and errors
// for misspelled ids, impossible states ("open" on a light) and desired values a
// domain cannot take. Fills the global TeobHouse interface declared in kernel/rule.ts.

import type { HaEntityState } from "@lambda-house/teob-ts/ha";

const ON_OFF = ["on", "off"];

/** States by domain where HA defines them; null = free text (numbers, names, ...). */
const DOMAIN_STATES: Record<string, string[]> = {
  alarm_control_panel: ["disarmed", "armed_home", "armed_away", "armed_night", "armed_vacation", "armed_custom_bypass", "pending", "arming", "disarming", "triggered"],
  automation: ON_OFF,
  binary_sensor: ON_OFF,
  cover: ["open", "closed", "opening", "closing"],
  fan: ON_OFF,
  humidifier: ON_OFF,
  input_boolean: ON_OFF,
  light: ON_OFF,
  lock: ["locked", "unlocked", "locking", "unlocking", "jammed", "open", "opening"],
  media_player: ["off", "on", "idle", "playing", "paused", "standby", "buffering"],
  remote: ON_OFF,
  script: ON_OFF,
  siren: ON_OFF,
  sun: ["above_horizon", "below_horizon"],
  switch: ON_OFF,
  update: ON_OFF,
  vacuum: ["cleaning", "docked", "idle", "paused", "returning", "error"],
  valve: ["open", "closed", "opening", "closing"],
};

const CLIMATE_MODES = ["off", "heat", "cool", "heat_cool", "auto", "dry", "fan_only"];

const strings = (v: unknown): string[] | undefined =>
  Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === "string") ? (v as string[]) : undefined;

/** The TypeScript type of one entity's state. */
export function stateType(s: Pick<HaEntityState, "entity_id" | "attributes">): string {
  const domain = s.entity_id.slice(0, s.entity_id.indexOf("."));
  const a = s.attributes ?? {};
  let states: string[] | undefined = DOMAIN_STATES[domain];
  if (domain === "climate") states = strings(a["hvac_modes"]) ?? CLIMATE_MODES;
  if (domain === "select" || domain === "input_select") states = strings(a["options"]);
  if (domain === "sensor" && a["device_class"] === "enum") states = strings(a["options"]);
  if (domain === "person" || domain === "device_tracker") return `"home" | "not_home" | (string & {})`;
  return states === undefined ? "string" : states.map((x) => JSON.stringify(x)).join(" | ");
}

/** One line of doc: name · device class or unit. */
function doc(s: HaEntityState): string {
  const a = s.attributes ?? {};
  const parts = [a["friendly_name"], a["device_class"], a["unit_of_measurement"]].filter(
    (x): x is string => typeof x === "string" && x.length > 0,
  );
  return parts.join(" · ").replace(/\*\//g, "* /").replace(/\s+/g, " ");
}

/**
 * The house's entities as TeobHouse, and the ones Teobeanie may operate as TeobOperable.
 * Pass only the entities in the house scope: anything else is then a type error.
 */
export function generateHouseTypes(states: Iterable<HaEntityState>, opts: { at?: number; operable?: Iterable<string> } = {}): string {
  const sorted = [...states].filter((s) => /^[a-z_]+\.[a-z0-9_]+$/.test(s.entity_id)).sort((a, b) => a.entity_id.localeCompare(b.entity_id));
  const lines = [
    `// ha.d.ts — this house's ${sorted.length} entities, generated by Teobeanie${opts.at ? ` on ${new Date(opts.at).toISOString().slice(0, 10)}` : ""}.`,
    "// Do not edit: regenerate it when entities are added, renamed or removed.",
    "",
    "export {};",
    "",
    "declare global {",
    "  interface TeobHouse {",
  ];
  for (const s of sorted) {
    const d = doc(s);
    if (d) lines.push(`    /** ${d} */`);
    lines.push(`    ${JSON.stringify(s.entity_id)}: ${stateType(s)};`);
  }
  lines.push("  }", "  interface TeobOperable {");
  const known = new Set(sorted.map((s) => s.entity_id));
  for (const id of [...(opts.operable ?? [])].filter((e) => known.has(e)).sort()) lines.push(`    ${JSON.stringify(id)}: true;`);
  lines.push("  }", "}", "");
  return lines.join("\n");
}
